/**
 * build/bundle.mjs — produce file://-safe browser artifacts from the ES-module sources.
 *
 * Why: ES `import` and JSON-module loading are blocked from `file://` origins
 * (CORS: origin "null"). To let the pages work when opened directly AND on any
 * host, we ship a single CLASSIC-script bundle (no import/export, no fetch) and
 * inline each page's definition.
 *
 * The ES-module sources stay canonical (Node gates use them). This regenerates:
 *   - /app.bundle.js                (classic IIFE -> window.PI)
 *   - /instruments/<id>.html        (loads bundle + inlined definition)
 *   - /viewer/viewer.html           (loads bundle + viewer glue)
 *
 * Run with: npm run build
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, resolve, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...s) => resolve(ROOT, ...s);

// Modules in dependency order; keys are repo-relative posix paths.
const MODULES = [
  'engine/dom.js',
  'engine/scoring.js',
  'engine/sections/info.js',
  'engine/sections/scored-likert.js',
  'engine/sections/self-rating.js',
  'engine/sections/select-and-commit.js',
  'engine/sections/free-reflection.js',
  'engine/engine.js',
  'engine/save-adapter.js',
  'instruments/instrument-page.js',
  'viewer/viewer.js',
  'viewer/viewer-page.js',
];

function transform(key, src) {
  const dir = posix.dirname(key);
  const exported = [];
  // collect exported names
  const re = /^[ \t]*export\s+(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z0-9_$]+)/gm;
  let m;
  while ((m = re.exec(src)) !== null) exported.push(m[1]);
  // rewrite imports -> __req destructuring
  let out = src.replace(
    /^[ \t]*import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm,
    (_full, names, rel) => {
      const target = posix.normalize(posix.join(dir, rel));
      const parts = names.split(',').map((n) => n.trim()).filter(Boolean).map((n) => {
        const mm = n.match(/^(\S+)\s+as\s+(\S+)$/);
        return mm ? `${mm[1]}: ${mm[2]}` : n;
      });
      return `const { ${parts.join(', ')} } = __req(${JSON.stringify(target)});`;
    }
  );
  // strip leading `export `
  out = out.replace(/^([ \t]*)export\s+/gm, '$1');
  return `__def(${JSON.stringify(key)}, function(__req){\n${out}\nreturn { ${exported.join(', ')} };\n});`;
}

const factories = MODULES.map((key) => transform(key, readFileSync(p(key), 'utf8'))).join('\n\n');

const bundle = `/* GENERATED by build/bundle.mjs — do not edit. Classic script, no import/export, no network. */
(function(){
  "use strict";
  var __mods = {}, __cache = {};
  function __def(name, factory){ __mods[name] = factory; }
  function __req(name){
    if (!(name in __cache)) { __cache[name] = {}; __cache[name] = __mods[name](__req); }
    return __cache[name];
  }

${factories}

  var PI = {};
  ['engine/scoring.js','engine/engine.js','engine/save-adapter.js','instruments/instrument-page.js','viewer/viewer.js','viewer/viewer-page.js']
    .forEach(function(k){ var m = __req(k); for (var key in m) PI[key] = m[key]; });
  (typeof window !== 'undefined' ? window : globalThis).PI = PI;
})();
`;

// self-check: no module syntax / network primitives leaked into the bundle
for (const bad of [/\bimport\s/, /\bexport\s/, /\bfetch\s*\(/, /XMLHttpRequest/]) {
  if (bad.test(bundle)) throw new Error('bundle self-check failed: contains ' + bad);
}
writeFileSync(p('app.bundle.js'), bundle);
console.log('wrote app.bundle.js (' + bundle.length + ' bytes)');

// ---- regenerate instrument pages (inline definition, classic scripts) ----
const safeJson = (obj) => JSON.stringify(obj).replace(/<\//g, '<\\/'); // safe inside <script>
const defFiles = readdirSync(p('definitions')).filter((f) => f.endsWith('.json'));
for (const f of defFiles) {
  const def = JSON.parse(readFileSync(p('definitions', f), 'utf8'));
  const page = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${def.title} — Personal Inventory</title>
  <link rel="stylesheet" href="instrument.css">
</head>
<body>
  <main class="pi-wrap"><div id="app"></div></main>
  <!-- GENERATED by build/bundle.mjs. file://-safe: classic bundle + inlined definition, no module import, no network. -->
  <script src="../app.bundle.js"></script>
  <script type="application/json" id="pi-def">${safeJson(def)}</script>
  <script>PI.mountInstrument(JSON.parse(document.getElementById('pi-def').textContent));</script>
</body>
</html>
`;
  writeFileSync(p('instruments', f.replace(/\.json$/, '.html')), page);
}
console.log('regenerated ' + defFiles.length + ' instrument page(s)');

